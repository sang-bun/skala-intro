# 사용자가 문장을 반복적으로 입력하고 그대로 출력하는 프로그램
# '!quit'을 입력하면 프로그램을 종료한다.

def main():
    # 사용자가 종료를 입력할 때까지 반복한다.
    while True:
        # 사용자로부터 문장을 입력받는다.
        text = input("문장을 입력하세요 (!quit 입력 시 종료): ")

        # 종료 명령을 입력하면 반복문을 종료한다.
        if text == "!quit":
            print("프로그램을 종료합니다.")
            break

        # 입력받은 문장을 그대로 출력한다.
        print(text)


# 프로그램의 시작점
if __name__ == "__main__":
    main()